# -*- coding: utf-8 -*-
import logging
from odoo import models, fields, api, _
from odoo.exceptions import UserError
from odoo.tools import html2plaintext

_logger = logging.getLogger(__name__)

FEEDBACK_SUMMARY_SYSTEM_PROMPT = """
You are a CRM assistant specializing in summarizing customer feedback and communication history.
Your task is to analyze all the messages and notes exchanged on a sales lead and produce a
concise, structured feedback summary.

The summary must:
- Be written in clear, professional language
- Highlight key customer sentiments, requests, and concerns
- Mention any follow-up actions or commitments mentioned
- Note the overall tone (positive, neutral, negative, mixed)
- Be concise (aim for 150-300 words)

Do NOT invent information. Only summarize what is present in the messages.
If there are no relevant messages, say so briefly.
"""


class CrmLead(models.Model):
    _inherit = 'crm.lead'

    feedback_summary = fields.Html(
        string="Feedback Summary",
        help="AI-generated summary of all feedback and communications on this lead.",
        readonly=True,
        copy=False,
    )
    feedback_summary_date = fields.Datetime(
        string="Summary Generated On",
        readonly=True,
        copy=False,
    )

    def action_generate_feedback_summary(self):
        """Collect chatter messages and generate a feedback summary via Mistral AI."""
        self.ensure_one()

        # Gather messages: emails, notes, and internal messages — skip automated ones
        messages = self.env['mail.message'].search([
            ('res_id', '=', self.id),
            ('model', '=', 'crm.lead'),
            ('message_type', 'in', ['email', 'comment', 'email_outgoing']),
            ('subtype_id', '!=', self.env.ref('mail.mt_activities').id),
        ], order='date asc')

        if not messages:
            raise UserError(_("There are no messages or notes on this lead to summarize."))

        # Build the message transcript
        transcript_lines = []
        for msg in messages:
            author = msg.author_id.name or msg.email_from or _("Unknown")
            date_str = fields.Datetime.to_string(msg.date)
            body = html2plaintext(msg.body or '').strip()
            if not body:
                continue
            transcript_lines.append(f"[{date_str}] {author}:\n{body}")

        if not transcript_lines:
            raise UserError(_("No message content found to summarize."))

        transcript = "\n\n---\n\n".join(transcript_lines)

        user_prompt = (
            f"Lead: {self.name}\n"
            f"Customer: {self.partner_name or self.partner_id.name or 'N/A'}\n"
            f"Stage: {self.stage_id.name or 'N/A'}\n\n"
            f"=== Communication History ===\n\n{transcript}\n\n"
            f"Please generate a feedback summary for this lead."
        )

        try:
            from odoo.addons.connect_mistral_ai.utils.llm_providers import MistralApi
            api = MistralApi(self.env)
            responses = api.request_llm(
                llm_model='mistral-small-latest',
                system_prompts=[FEEDBACK_SUMMARY_SYSTEM_PROMPT],
                user_prompts=[user_prompt],
                temperature=0.3,
            )
            raw_summary = "\n\n".join(responses).strip()
        except Exception as e:
            _logger.exception("Error generating feedback summary for lead %s", self.id)
            raise UserError(_("Failed to generate feedback summary: %s") % str(e))

        # Convert plain text response to simple HTML paragraphs
        html_summary = "".join(
            f"<p>{line}</p>" for line in raw_summary.split("\n") if line.strip()
        )

        self.write({
            'feedback_summary': html_summary,
            'feedback_summary_date': fields.Datetime.now(),
        })

        # Log a note in the chatter
        self.message_post(
            body=_("Feedback summary generated by AI on %s.") % fields.Datetime.to_string(
                self.feedback_summary_date
            ),
            subtype_xmlid='mail.mt_note',
        )

        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _("Feedback Summary Generated"),
                'message': _("The feedback summary has been successfully generated."),
                'type': 'success',
                'sticky': False,
            },
        }
